/**
 * The interface's own words, in the reader's own language (Phase L).
 *
 * WHERE THE LINE BETWEEN THIS FILE AND THE SERVER FALLS
 *
 * The two catalogues are DISJOINT, and that is the whole arrangement:
 *
 *   the server owns every sentence ABOUT AN INVOICE -- why one is held, what
 *   state it is in, what an account problem is, what the assistant answers.
 *   Those are statements about records, they have to agree with the audit
 *   trail, and they are translated in `backend/i18n.py`.
 *
 *   this file owns the CHROME -- nav rows, buttons, column headers, empty
 *   states, the sign-in box. Those are statements about the interface. The
 *   server has no business writing them and does not.
 *
 * So no string is translated in two places, and there is no pair of
 * catalogues that could disagree about the same sentence. The one thing they
 * do share is WHICH LANGUAGES EXIST, and that is served by the server
 * (`/api/auth/me` and `/api/portal/me` carry `languages`) so a picker can
 * never offer a language the backend has no catalogue for.
 *
 * HOW THE CHOICE REACHES THE SERVER
 *
 * `Accept-Language` is a forbidden header name -- `fetch` cannot set it -- so
 * a stored preference travels as `?lang=` on every request, which is exactly
 * the parameter `main.request_locale` gives precedence to. Without a stored
 * choice nothing is appended and the browser's own Accept-Language decides,
 * which is the right default for someone who has never touched the picker.
 *
 * FALLBACK IS PER KEY, NOT PER LANGUAGE. A catalogue that is missing an entry
 * yields the English one rather than an empty span, and an unknown key yields
 * the key -- visible, and therefore fixed, rather than silently blank.
 */
