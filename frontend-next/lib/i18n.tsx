/* --------------------------------------------------------------- storage */

/** The stored preference, or "" when the reader has never picked one.
 *
 *  "" is a real state and not a missing value: it means "use the browser's own
 *  Accept-Language", which is what someone who has never opened the picker
 *  actually wants. Only an explicit choice is written, and only an explicit
 *  choice is sent to the server as `?lang=`. */
export function storedLocale(): string {
  if (typeof window === "undefined") return "";
  try {
    const v = localStorage.getItem(LOCALE_KEY) || "";
    return (LOCALES as readonly string[]).includes(v) ? v : "";
  } catch {
    return "";
  }
}

function writeLocale(tag: string) {
  try {
    localStorage.setItem(LOCALE_KEY, tag);
  } catch {
    /* private mode: the choice applies for this page and is not remembered */
  }
}

/** The browser's own first choice, narrowed to what this bundle carries.
 *  Used only to render the FIRST paint correctly -- the server does its own,
 *  authoritative negotiation over the same header for everything it writes. */
function browserLocale(): string {
  if (typeof navigator === "undefined") return DEFAULT_LOCALE;
  for (const raw of navigator.languages || [navigator.language || ""]) {
    const base = String(raw || "").toLowerCase().split("-")[0];
    if ((LOCALES as readonly string[]).includes(base)) return base;
  }
  return DEFAULT_LOCALE;
}

/* -------------------------------------------------------------- provider */

type Ctx = {
  locale: string;
  /** "" when nothing was ever chosen -- see `storedLocale`. */
  chosen: string;
  setLocale: (tag: string) => void;
  t: (key: MessageKey) => string;
};

const I18nContext = createContext<Ctx>({
  locale: DEFAULT_LOCALE,
  chosen: "",
  setLocale: () => {},
  t: (key) => EN[key] ?? key,
});

export function I18nProvider({ children }: { children: React.ReactNode }) {
  // Starts at English on both server and first client render, so a static
  // export hydrates without a mismatch, then settles on the real preference in
  // an effect. The same shape ThemeProvider uses, for the same reason.
  const [locale, setLocaleState] = useState<string>(DEFAULT_LOCALE);
  const [chosen, setChosen] = useState<string>("");

  useEffect(() => {
    const stored = storedLocale();
    setChosen(stored);
    setLocaleState(stored || browserLocale());
  }, []);

  useEffect(() => {
    // Keep <html lang> honest. It is what a screen reader picks a voice from
    // and what a browser offers to translate against, and leaving it at "en"
    // over a page of German is a straightforwardly wrong statement.
    document.documentElement.setAttribute("lang", locale);
  }, [locale]);

  const setLocale = useCallback((tag: string) => {
    const next = (LOCALES as readonly string[]).includes(tag) ? tag : DEFAULT_LOCALE;
    writeLocale(next);
    setChosen(next);
    setLocaleState(next);
    // A full reload rather than a re-render, and deliberately so: every
    // server-written sentence already on screen -- why an invoice is held,
    // what its state is -- was rendered in the previous language and can only
    // be re-fetched, not re-translated here. Reloading gets the whole page,
    // both catalogues, into one language instead of leaving it in two.
    window.location.reload();
  }, []);

  const t = useCallback(
    (key: MessageKey) => CATALOGUES[locale]?.[key] ?? EN[key] ?? key,
    [locale]
  );

  return (
    <I18nContext.Provider value={{ locale, chosen, setLocale, t }}>
      {children}
    </I18nContext.Provider>
  );
}

export const useI18n = () => useContext(I18nContext);

/** Shorthand for the common case: `const t = useT();  t("nav.invoices")`. */
export const useT = () => useI18n().t;
